// Avaliações de EXEMPLO (só teste visual; trocar pelas reais antes de vender).
// Geradas sempre iguais a partir do id, então a página do produto, a loja e o checkout mostram os mesmos números.
function avaliacoesDe(p) {
  if (Array.isArray(p.avaliacoesDetalhadas)) {
    return p.avaliacoesDetalhadas.map(r => ({
      ...r,
      cor: r.cor || '#e7e7e9',
      data: new Date(`${r.data}T12:00:00`),
      fotos: r.fotos || [],
      item: r.item || 'Padrão',
      util: r.util || 0,
    }));
  }
  if (!p.exemplo) return [];
  let seed = [...p.id].reduce((a, c) => (a * 31 + c.charCodeAt(0)) % 2147483647, 7) || 42;
  const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
  const pick = a => a[Math.floor(rnd() * a.length)];
  const nomes = ['R**o S**a', 'J**a M**s', 'C**s A**e', 'F**a L**a', 'P**o H**e', 'A**a C**a', 'M**a F**s', 'L**s P**a', 'G**a R**s', 'T**o B**o', 'D**a N**s', 'V**a M**a', 'E**o C**o', 'B**a T**s', 'K**n S**a', 'R**a L**e', 'H**o A**s', 'S**a O**a', 'W**n G**s', 'N**a P**o'];
  const cores = ['#f6c1cc', '#c7dcf7', '#cdeccf', '#f7e3b5', '#dccdf3', '#f4d3c4'];
  const itens = p.pagina && p.pagina.opcoes ? p.pagina.opcoes[0].valores.filter(v => !v.esgotado).map(v => v.nome) : (p.itensAvaliacao || ['Padrão']);
  const textos = {}, pos = {};
  Object.entries(p.exemplo.textos).forEach(([n, a]) => { textos[n] = [...a]; pos[n] = 0; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [textos[n][i], textos[n][j]] = [textos[n][j], textos[n][i]]; } });
  const notas = [5, 4, 3, 2, 1].flatMap(n => Array(p.exemplo.dist[n] || 0).fill(n));
  const hoje = new Date();
  const lista = notas.map((n, i) => {
    const comTexto = n < 5 || rnd() < 0.45;
    const d = new Date(hoje); d.setDate(d.getDate() - Math.floor(i * 1.1 + rnd() * 2));
    const t = textos[n] || textos[5];
    return { nome: pick(nomes), cor: pick(cores), nota: n, texto: comTexto && t ? t[pos[n] = (pos[n] || 0) + 1, (pos[n] - 1) % t.length] : '', item: pick(itens), data: d, fotos: [], util: Math.floor(rnd() * 12) };
  });
  const datas = lista.map(r => r.data);
  for (let i = lista.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [lista[i], lista[j]] = [lista[j], lista[i]]; }
  lista.forEach((r, i) => r.data = datas[i]);
  return lista;
}

// Nota e nº de avaliações de cada produto; a loja soma tudo.
LOJA.avaliacoes = { total: 0, visuais: 0, 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 };
LOJA.vendidos = 0;
PRODUTOS.forEach(p => {
  const av = avaliacoesDe(p);
  const distribuicao = p.distribuicaoAvaliacoes;
  if (distribuicao) {
    p.avaliacoes = [5, 4, 3, 2, 1].reduce((s, n) => s + (distribuicao[n] || 0), 0);
    p.nota = p.avaliacoes
      ? Math.round([5, 4, 3, 2, 1].reduce((s, n) => s + n * (distribuicao[n] || 0), 0) / p.avaliacoes * 10) / 10
      : 0;
    [5, 4, 3, 2, 1].forEach(n => { LOJA.avaliacoes[n] += distribuicao[n] || 0; });
    av.forEach(r => { if (r.fotos.length) LOJA.avaliacoes.visuais++; });
  } else {
    p.avaliacoes = av.length;
    p.nota = av.length ? Math.round(av.reduce((a, r) => a + r.nota, 0) / av.length * 10) / 10 : 0;
    av.forEach(r => { LOJA.avaliacoes[r.nota]++; if (r.fotos.length) LOJA.avaliacoes.visuais++; });
  }
  LOJA.avaliacoes.total += p.avaliacoes;
  LOJA.vendidos += p.vendidos;
});

// ===== CÁLCULO DO PEDIDO (o mesmo no produto, no checkout e no servidor) =====
// itens: [{ id, var, qtd }] · resgatados: ids de cupons resgatados · pix: true aplica 5%.
function precoItem(p, v) { const x = p.precos && p.precos[v]; return { preco: x ? x.preco : p.preco, precoDe: (x ? x.precoDe : p.precoDe) || null, img: x && x.img || p.img }; }
function descontoCupom(c, base, qtd) {
  if (base < (c.min || 0)) return 0;
  const d = c.valor ? c.valor * (c.porUnidade ? qtd : 1) : base * (c.pct || 0) / 100;
  return Math.round(Math.min(c.max || Infinity, d, base) * 100) / 100;
}
function calculaPedido(itens, resgatados, pix) {
  const r = new Set(resgatados || []);
  const ativo = c => c.auto || r.has(c.id);
  const linhas = itens.map(i => {
    const p = PRODUTOS.find(x => x.id === i.id); if (!p) return null;
    const qtd = Math.max(1, Math.min(12, parseInt(i.qtd, 10) || 1));
    const pi = precoItem(p, i.var || '');
    const base = pi.preco * qtd;
    let resto = base; const aplicados = [];
    (p.cupons || []).forEach(c => { if (!ativo(c)) return; const d = Math.min(descontoCupom(c, base, qtd), resto); if (d > 0) { resto -= d; aplicados.push({ ...c, desconto: d, produto: p.id }); } });
    return { id: p.id, var: i.var || '', qtd, p, ...pi, base, cupons: aplicados, liquido: Math.round(resto * 100) / 100 };
  }).filter(Boolean);
  const sub = linhas.reduce((s, l) => s + l.base, 0);
  const orig = linhas.reduce((s, l) => s + (l.precoDe || l.preco) * l.qtd, 0);
  let liquido = linhas.reduce((s, l) => s + l.liquido, 0);
  const cuponsLoja = [];
  (LOJA.cupons || []).forEach(c => { if (!ativo(c)) return; const d = descontoCupom(c, liquido, 1); if (d > 0) { liquido -= d; cuponsLoja.push({ ...c, desconto: d }); } });
  const cupons = linhas.flatMap(l => l.cupons).concat(cuponsLoja);
  const totalCupons = Math.round(cupons.reduce((s, c) => s + c.desconto, 0) * 100) / 100;
  const descPix = pix ? Math.round(liquido * 0.05 * 100) / 100 : 0;
  const total = Math.round((liquido - descPix) * 100) / 100;
  return { linhas, sub, orig, descProduto: Math.round((orig - sub) * 100) / 100, cupons, totalCupons, descPix, total, economia: Math.round((orig - total) * 100) / 100, n: linhas.reduce((s, l) => s + l.qtd, 0) };
}
// todos os cupons que valem para estes produtos (produto + loja), para mostrar e resgatar
function cuponsDisponiveis(ids) {
  return PRODUTOS.filter(p => ids.includes(p.id)).flatMap(p => (p.cupons || []).map(c => ({ ...c, produto: p.id, produtoTitulo: p.titulo }))).concat((LOJA.cupons || []).map(c => ({ ...c, produto: null })));
}

